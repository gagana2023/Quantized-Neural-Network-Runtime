"""M2 tests: the executor on a tiny graph and, when the models exist, end to end against ORT."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import onnxruntime as ort
import pytest
from onnx import TensorProto as TP
from onnx import helper, numpy_helper

from int8rt.executor import Executor
from int8rt.graph import Graph
from int8rt.importer import graph_from_model, load_model

ROOT = Path(__file__).resolve().parent.parent
CIFAR = ROOT / "models" / "cifar" / "cifar_int8.onnx"
KWS = ROOT / "models" / "kws" / "kws" / "dscnn_int8.onnx"
KWS_FEATURES = ROOT / "models" / "kws" / "kws" / "kws_test_features.npz"


def tiny_graph() -> Graph:
    """float -> QuantizeLinear -> MaxPool -> Flatten -> DequantizeLinear."""
    inits = [
        numpy_helper.from_array(np.float32(0.5), "s"),
        numpy_helper.from_array(np.int8(0), "z"),
    ]
    nodes = [
        helper.make_node("QuantizeLinear", ["f", "s", "z"], ["q"]),
        helper.make_node("MaxPool", ["q"], ["p"], kernel_shape=[2, 2], strides=[2, 2]),
        helper.make_node("Flatten", ["p"], ["fl"]),
        helper.make_node("DequantizeLinear", ["fl", "s", "z"], ["y"]),
    ]
    g = helper.make_graph(
        nodes,
        "t",
        [helper.make_tensor_value_info("f", TP.FLOAT, [1, 1, 4, 4])],
        [helper.make_tensor_value_info("y", TP.FLOAT, [1, 4])],
        inits,
    )
    m = helper.make_model(g, opset_imports=[helper.make_opsetid("", 17)])
    m.ir_version = 10
    return graph_from_model(m)


def test_runs_a_tiny_graph_by_hand() -> None:
    x = (np.arange(16, dtype=np.float32).reshape(1, 1, 4, 4) - 8) / 2  # -4.0 ... 3.5
    out = Executor(tiny_graph()).run({"f": x})["y"]
    # quantised (scale 0.5) = 2x = -8 ... 7; the 2x2 maxima are -3, -1, 5, 7; times 0.5
    assert out.tolist() == [[-1.5, -0.5, 2.5, 3.5]]
    assert out.dtype == np.float32


def test_outputs_are_copies_and_runs_are_repeatable() -> None:
    ex = Executor(tiny_graph())
    x = np.linspace(-3, 3, 16, dtype=np.float32).reshape(1, 1, 4, 4)
    first = ex.run({"f": x})["y"]
    saved = first.copy()
    first[...] = 99  # must not corrupt the executor's internal buffers
    assert np.array_equal(ex.run({"f": x})["y"], saved)


def test_validates_inputs() -> None:
    ex = Executor(tiny_graph())
    with pytest.raises(ValueError, match="expected inputs"):
        ex.run({})
    with pytest.raises(ValueError, match="expected float32"):
        ex.run({"f": np.zeros((1, 1, 4, 4), dtype=np.float64)})
    with pytest.raises(ValueError, match="expected float32"):
        ex.run({"f": np.zeros((1, 1, 2, 2), dtype=np.float32)})


def test_greedy_planner_is_not_available_until_m4() -> None:
    with pytest.raises(NotImplementedError):
        Executor(tiny_graph(), planner="greedy")


def test_dump_dir_writes_every_tensor_and_an_index(tmp_path: Path) -> None:
    x = np.zeros((1, 1, 4, 4), dtype=np.float32)
    Executor(tiny_graph(), dump_dir=tmp_path).run({"f": x})
    index = json.loads((tmp_path / "index.json").read_text())
    assert list(index) == ["f", "q", "p", "fl", "y"]  # execution order
    assert np.load(tmp_path / index["q"]).dtype == np.int8
    assert np.load(tmp_path / index["p"]).shape == (1, 1, 2, 2)


def _ort(path: Path) -> ort.InferenceSession:
    so = ort.SessionOptions()
    so.graph_optimization_level = ort.GraphOptimizationLevel.ORT_DISABLE_ALL
    return ort.InferenceSession(str(path), so, providers=["CPUExecutionProvider"])


@pytest.mark.skipif(not CIFAR.exists(), reason="models/ is generated by tools/export_quantize.py")
def test_cifar_logits_match_ort_on_random_inputs() -> None:
    ex, sess = Executor(load_model(CIFAR)), _ort(CIFAR)
    rng = np.random.default_rng(0)
    for _ in range(5):
        x = rng.standard_normal((1, 3, 32, 32)).astype(np.float32)
        ref = sess.run(None, {"input": x})[0]
        assert ex.run({"input": x})["logits"].tobytes() == ref.tobytes()


@pytest.mark.skipif(
    not (KWS.exists() and KWS_FEATURES.exists()), reason="KWS model comes from Project 2"
)
def test_kws_logits_match_ort_on_real_features() -> None:
    ex, sess = Executor(load_model(KWS)), _ort(KWS)
    for x in np.load(KWS_FEATURES)["x"][:5]:
        feed = x[None].astype(np.float32)
        ref = sess.run(None, {"mfcc": feed})[0]
        assert ex.run({"mfcc": feed})["logits"].tobytes() == ref.tobytes()
