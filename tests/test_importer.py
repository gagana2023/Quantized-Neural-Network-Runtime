"""M2 tests: the importer, on tiny hand-built models and (when present) the real ones."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import onnx
import pytest
from onnx import TensorProto as TP
from onnx import helper, numpy_helper

from int8rt.importer import graph_from_model, load_model
from int8rt.ops import UnsupportedError

ROOT = Path(__file__).resolve().parent.parent
CIFAR = ROOT / "models" / "cifar" / "cifar_int8.onnx"
KWS = ROOT / "models" / "kws" / "kws" / "dscnn_int8.onnx"


def _model(
    nodes: list[onnx.NodeProto],
    in_shape: list[int | str],
    out_shape: list[int],
    in_type: int = TP.INT8,
    out_type: int = TP.INT8,
    inits: list[onnx.TensorProto] | None = None,
    in_name: str = "x",
) -> onnx.ModelProto:
    g = helper.make_graph(
        nodes,
        "t",
        [helper.make_tensor_value_info(in_name, in_type, in_shape)],
        [helper.make_tensor_value_info("y", out_type, out_shape)],
        inits or [],
    )
    m = helper.make_model(g, opset_imports=[helper.make_opsetid("", 17)])
    m.ir_version = 10
    return m


def test_imports_pool_and_flatten_with_computed_shapes() -> None:
    nodes = [
        helper.make_node("MaxPool", ["x"], ["p"], kernel_shape=[2, 2], strides=[2, 2]),
        helper.make_node("Flatten", ["p"], ["y"], axis=1),
    ]
    g = graph_from_model(_model(nodes, [1, 2, 4, 4], [1, 8]))
    assert [n.op_type for n in g.nodes] == ["MaxPool", "Flatten"]
    assert g.tensors["p"].shape == (1, 2, 2, 2) and g.tensors["y"].shape == (1, 8)
    assert g.inputs == ["x"] and g.outputs == ["y"]
    assert g.producer_index() == {"p": 0, "y": 1}


def test_quantize_output_gets_scale_and_zero_point_and_pool_inherits_them() -> None:
    inits = [
        numpy_helper.from_array(np.float32(0.5), "s"),
        numpy_helper.from_array(np.int8(-3), "z"),
    ]
    nodes = [
        helper.make_node("QuantizeLinear", ["f", "s", "z"], ["q"]),
        helper.make_node("MaxPool", ["q"], ["y"], kernel_shape=[1, 1]),
    ]
    m = _model(nodes, [1, 1, 2, 2], [1, 1, 2, 2], in_type=TP.FLOAT, inits=inits, in_name="f")
    graph = graph_from_model(m)
    for name in ("q", "y"):
        assert graph.tensors[name].scale == np.float32(0.5)
        assert graph.tensors[name].zero_point == -3
    assert graph.tensors["s"].is_initializer and not graph.tensors["q"].is_initializer


def test_rejects_unsupported_ops_and_lists_all_of_them() -> None:
    nodes = [helper.make_node("Relu", ["x"], ["a"]), helper.make_node("Neg", ["a"], ["y"])]
    with pytest.raises(UnsupportedError, match=r"ai\.onnx\.Neg, ai\.onnx\.Relu"):
        graph_from_model(_model(nodes, [1, 4], [1, 4]))


def test_rejects_dynamic_and_missing_shapes() -> None:
    nodes = [helper.make_node("Flatten", ["x"], ["y"])]
    with pytest.raises(UnsupportedError, match="dynamic"):
        graph_from_model(_model(nodes, ["batch", 4], [1, 4]))
    with pytest.raises(UnsupportedError, match="dynamic"):
        graph_from_model(_model(nodes, [0, 4], [1, 4]))


def test_rejects_unsupported_attributes() -> None:
    nodes = [helper.make_node("MaxPool", ["x"], ["y"], kernel_shape=[2, 2], ceil_mode=1)]
    with pytest.raises(UnsupportedError, match="ceil_mode"):
        graph_from_model(_model(nodes, [1, 1, 4, 4], [1, 1, 2, 2]))
    nodes = [helper.make_node("MaxPool", ["x"], ["y"], kernel_shape=[2, 2], strange=1)]
    with pytest.raises(UnsupportedError, match="strange"):
        graph_from_model(_model(nodes, [1, 1, 4, 4], [1, 1, 2, 2]))


def test_rejects_declared_shape_that_disagrees_with_computed_shape() -> None:
    nodes = [helper.make_node("MaxPool", ["x"], ["y"], kernel_shape=[2, 2], strides=[2, 2])]
    with pytest.raises(UnsupportedError, match="disagrees"):
        graph_from_model(_model(nodes, [1, 1, 4, 4], [1, 1, 3, 3]))


def test_rejects_non_trailing_reduce_mean() -> None:
    node = helper.make_node("ReduceMean", ["f"], ["y"], axes=[1], keepdims=0)
    m = _model([node], [2, 3, 4], [2, 4], in_type=TP.FLOAT, out_type=TP.FLOAT, in_name="f")
    with pytest.raises(UnsupportedError, match="non-trailing"):
        graph_from_model(m)


def test_rejects_input_produced_later() -> None:
    nodes = [
        helper.make_node("Flatten", ["a"], ["y"]),
        helper.make_node("Flatten", ["x"], ["a"]),
    ]
    with pytest.raises(UnsupportedError, match="not produced earlier"):
        graph_from_model(_model(nodes, [1, 4], [1, 4]))


@pytest.mark.skipif(not CIFAR.exists(), reason="models/ is generated by tools/export_quantize.py")
def test_imports_cifar_model() -> None:
    g = load_model(CIFAR)
    assert len(g.nodes) == 11 and g.inputs == ["input"] and g.outputs == ["logits"]
    assert g.tensors["input"].shape == (1, 3, 32, 32)
    first_conv = next(n for n in g.nodes if n.op_type == "QLinearConv")
    assert g.tensors[first_conv.outputs[0]].dtype == np.int8
    assert g.tensors[first_conv.outputs[0]].scale is not None


@pytest.mark.skipif(not KWS.exists(), reason="KWS model is copied from Project 2 into models/kws")
def test_imports_kws_model() -> None:
    g = load_model(KWS)
    ops = [n.op_type for n in g.nodes]
    assert ops.count("QLinearConv") == 9 and ops.count("ReduceMean") == 1
    assert g.tensors["mfcc"].shape == (1, 1, 49, 10)
    assert g.tensors["logits"].dtype == np.float32
