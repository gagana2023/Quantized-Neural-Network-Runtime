"""M3 tests: the parity tool's comparison logic, and a short end-to-end run on both models."""

from __future__ import annotations

import numpy as np
import pytest

from int8rt.graph import Node
from tools.compare_ort import (
    MODELS,
    DeviationStats,
    compare_in_order,
    first_diff_index,
    run_accuracy,
    run_parity,
    tapped_session,
)


def _node(name: str, out: str, op: str = "QLinearConv") -> Node:
    return Node(name, op, "", ["x"], [out])


def test_first_diff_index_finds_first_element_in_c_order() -> None:
    a = np.zeros((2, 3, 4), dtype=np.int8)
    b = a.copy()
    assert first_diff_index(a, b) is None
    b[1, 0, 2] = 5
    b[1, 2, 3] = -7
    assert first_diff_index(a, b) == (1, 0, 2)


def test_float_tensors_compare_by_bit_pattern() -> None:
    a = np.array([1.0, np.nan, 0.0], dtype=np.float32)
    assert first_diff_index(a, a.copy()) is None  # NaN equals itself bit for bit
    b = a.copy()
    b[2] = -0.0  # equal as numbers, different bytes
    assert first_diff_index(a, b) == (2,)
    c = a.copy()
    c[0] = np.nextafter(np.float32(1.0), np.float32(2.0))  # 1 ULP
    assert first_diff_index(a, c) == (0,)


def test_shape_or_dtype_mismatch_is_an_error_not_a_pass() -> None:
    with pytest.raises(ValueError, match="mismatch"):
        first_diff_index(np.zeros(4, dtype=np.int8), np.zeros(4, dtype=np.uint8))


def test_compare_in_order_reports_the_first_divergent_node_with_values() -> None:
    nodes = [_node("n0", "t0"), _node("n1", "t1", "MaxPool"), _node("n2", "t2")]
    ref = {t: np.arange(6, dtype=np.int8).reshape(2, 3) for t in ("t0", "t1", "t2")}
    got = {t: v.copy() for t, v in ref.items()}
    flags, div = compare_in_order(nodes, ref, got)
    assert flags == [True, True, True] and div is None

    got["t1"][1, 2] = 99  # corrupt n1 ...
    got["t2"][0, 0] = -3  # ... and, independently, n2
    flags, div = compare_in_order(nodes, ref, got)
    assert flags == [True, False, False]  # every node is still compared
    assert div is not None
    assert (div.node, div.op, div.tensor, div.index) == ("n1", "MaxPool", "t1", (1, 2))
    assert (div.ref_value, div.got_value) == (5, 99)


def test_deviation_stats_on_a_hand_example() -> None:
    ref = np.array([0, 10, -128, 127], dtype=np.int8)
    got = np.array([0, 11, -127, 125], dtype=np.int8)  # diffs 0, +1, +1, -2
    s = DeviationStats()
    s.add(ref, got)
    d = s.as_dict()
    assert d["elements"] == 4 and d["differing_elements"] == 3
    assert d["differing_percent"] == 75.0 and d["max_abs_difference"] == 2.0
    assert d["difference_histogram"] == {"-2": 1, "1": 2}


@pytest.mark.parametrize("name", ["cifar", "kws"])
def test_tapped_session_exposes_every_node_output(name: str) -> None:
    spec = MODELS[name]
    if not spec.int8_path.exists():
        pytest.skip("models/ is generated by tools/export_quantize.py (KWS: from Project 2)")
    import onnx

    sess, taps = tapped_session(spec.int8_path)
    n_nodes = len(onnx.load(str(spec.int8_path)).graph.node)
    assert len(taps) == n_nodes - 1  # the last node's output is already a graph output
    assert len(sess.get_outputs()) == n_nodes


@pytest.mark.parametrize("name", ["cifar", "kws"])
def test_float_mode_is_bit_exact_on_every_layer_for_a_few_inputs(name: str) -> None:
    spec = MODELS[name]
    if not spec.int8_path.exists():
        pytest.skip("models/ is generated by tools/export_quantize.py (KWS: from Project 2)")
    if name == "cifar":  # random inputs: the real test set needs the dataset download
        images = np.random.default_rng(0).standard_normal((3, 3, 32, 32)).astype(np.float32)
    else:
        images = np.load(MODELS["kws"].int8_path.parent / "kws_test_features.npz")["x"][:3]
    res = run_parity(spec, images, 3)
    assert res.all_exact, res.report["first_mismatch"]
    assert res.report["layers_compared"] == len(res.report["layers"])
    assert res.report["exact_matches"] == res.report["tensor_comparisons"]
    iso = res.report["mode_b_vs_mode_a"]["isolated"]
    # a single fixed-point requantiser can be at most 1 LSB from the float one on int8 outputs
    for row in iso:
        if row["unit"] == "LSB":
            assert row["max_abs_difference"] <= 1, row


def test_accuracy_pass_runs_on_a_tiny_kws_subset() -> None:
    spec = MODELS["kws"]
    npz = spec.int8_path.parent / "kws_test_features.npz"
    if not (spec.int8_path.exists() and npz.exists()):
        pytest.skip("KWS model comes from Project 2")
    d = np.load(npz)
    acc = run_accuracy(spec, d["x"][:5], d["y"][:5])
    assert acc["test_images"] == 5
    assert acc["float_mode_logits_bit_exact_with_ort_int8"] == {"inputs": 5, "of": 5}
